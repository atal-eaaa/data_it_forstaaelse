# Vi har to variable x og y, som vi tester på i en betingelse:
x=0
y=0

if x > y:
    print("x er større end y")
if x >= y:
    print("x er større end eller lig med y")
if x < y:
    print("x er mindre end y")
if x <= y:
    print("x er mindre end eller lig med y")
if x == y:
    print("x er lig med y")
if x != y:
    print("x er forskellig fra  y")